const D2R = Math.PI / 180;
function distKm(lat1, lon1, lat2, lon2) {
  const dp = (lat2 - lat1) * D2R, dl = (lon2 - lon1) * D2R;
  const a = Math.sin(dp / 2) ** 2 + Math.cos(lat1 * D2R) * Math.cos(lat2 * D2R) * Math.sin(dl / 2) ** 2;
  return 12742 * Math.asin(Math.min(1, Math.sqrt(a)));
}

/** Upper case, ASCII (diacritics folded), punctuation → space, collapsed whitespace. */
export function normalizeText(s) {
  if (s == null) return '';
  return String(s).normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[ßẞ]/g, 'SS').replace(/[øØ]/g, 'O').replace(/[æÆ]/g, 'AE').replace(/[åÅ]/g, 'A').replace(/[łŁ]/g, 'L').replace(/[đĐ]/g, 'D')
    .toUpperCase().replace(/@+/g, ' ').replace(/['’`´.]/g, '').replace(/[^A-Z0-9]+/g, ' ').trim().replace(/\s+/g, ' ');
}

/** Parse the built-in table → [{locode, name, lat, lon, r, aliases}]. */
export function builtinPorts() {
  const out = [];
  for (const line of PORT_TABLE.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [locode, name, lat, lon, r, aliases] = line.split('|');
    out.push({ locode: locode.trim(), name: name.trim(), lat: +lat, lon: +lon, r: r && r.trim() ? +r : 3,
      aliases: (aliases || '').split(',').map((a) => a.trim()).filter(Boolean) });
  }
  return out;
}

/** Bounded Damerau-Levenshtein (optimal string alignment). Returns max + 1 when the distance exceeds `max`. */
function editDistance(a, b, max) {
  const la = a.length, lb = b.length;
  if (Math.abs(la - lb) > max) return max + 1;
  let prev2 = null, prev = new Array(lb + 1), cur = new Array(lb + 1);
  for (let j = 0; j <= lb; j++) prev[j] = j;
  for (let i = 1; i <= la; i++) {
    cur[0] = i; let rowMin = i;
    for (let j = 1; j <= lb; j++) {
      const cost = a.charCodeAt(i - 1) === b.charCodeAt(j - 1) ? 0 : 1;
      let v = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost);
      if (prev2 && i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) v = Math.min(v, prev2[j - 2] + 1);
      cur[j] = v; if (v < rowMin) rowMin = v;
    }
    if (rowMin > max) return max + 1;
    const t = prev2 || new Array(lb + 1); prev2 = prev; prev = cur; cur = t;
  }
  return prev[lb];
}

/** Words that join a compound place name ('BERGEN OP ZOOM', 'FRANKFURT AM MAIN'): their neighbours are not ports. */
const CONNECT = new Set(['OP', 'AAN', 'AM', 'AN', 'IM', 'UPON', 'ON', 'SUR', 'BEI', 'BIJ', 'DER', 'DEN', 'DI', 'DEL', 'SOBRE']);
const HOMONYM_KM = 50;

/**
 * Build a port index from the game's harbours plus the built-in table.
 * Returns `{ ports, byLocode, resolveDestination(raw, lat?, lon?), nearestPort(lat, lon, {maxKm}), port(key) }`.
 * A port entry: `{ key, locode|null, harbor|null, name, lat, lon, r (km) }`; `key` = harbour id when the port is (or is
 * linked to) a game harbour, else its LOCODE.
 */
export function createPortIndex(harbors = HARBORS) {
  const ports = [];
  const byLocode = new Map();
  const byKey = new Map();
  const names = new Map(); // normalized name/alias → port (first wins: built-in names, then harbour tokens)
  const compact = new Map(); // same without spaces ('RDAM', 'RTDM')
  const compactName = new Map(); // compact key → the name it came from
  const homonyms = new Map(); // normalized name → [ports far apart that share it] ('PORTLAND', 'NEWCASTLE', 'WILLEMSTAD')
  const addName = (n, p) => { // first registration wins: built-in names and aliases before harbour name tokens
    const k = normalizeText(n);
    if (!k || k.length < 2) return;
    const cur = names.get(k);
    if (!cur) names.set(k, p);
    else if (cur !== p && distKm(cur.lat, cur.lon, p.lat, p.lon) > HOMONYM_KM) {
      const g = homonyms.get(k) || [cur];
      if (!g.includes(p)) g.push(p);
      homonyms.set(k, g);
    }
    const c = k.replace(/ /g, '');
    if (c.length >= 3 && !compact.has(c)) { compact.set(c, p); compactName.set(c, k); }
  };
  const harborList = Array.isArray(harbors) ? harbors.filter((h) => h && Number.isFinite(h.lat) && Number.isFinite(h.lon) && h.id) : [];
  const tokensOf = (h) => new Set([h.name, ...String(h.name).split(/[/(),]/)].map(normalizeText).filter(Boolean));
  const harborTokens = new Map(harborList.map((h) => [h.id, tokensOf(h)]));
  // 1) built-in ports, linked to a game harbour: the nearest one within max(8 km, own radius), else the nearest one
  //    within 100 km that carries the port's name ('Shanghai (Yangshan)', 'Marseille (Fos)', 'IJmuiden / Amsterdam')
  for (const b of builtinPorts()) {
    const myNames = [b.name, b.name.replace(/\s*\(.*\)\s*/g, ''), ...b.aliases].map(normalizeText);
    let near = null, nearD = Infinity, named = null, namedD = Infinity;
    for (const h of harborList) {
      const d = distKm(b.lat, b.lon, h.lat, h.lon);
      if (d < nearD) { nearD = d; near = h; }
      if (d < namedD && d <= 100 && myNames.some((n) => harborTokens.get(h.id).has(n))) { namedD = d; named = h; }
    }
    const harbor = near && nearD <= Math.max(8, b.r) ? near.id : named ? named.id : null;
    const p = { key: harbor || b.locode, locode: b.locode, harbor, name: b.name, lat: b.lat, lon: b.lon, r: b.r };
    ports.push(p); byLocode.set(b.locode, p);
    if (!byKey.has(p.key)) byKey.set(p.key, p);
    addName(b.name, p); addName(b.name.replace(/\s*\(.*\)\s*/g, ''), p);
    for (const a of b.aliases) addName(a, p);
  }
  // 2) game harbours: every name token ('IJmuiden / Amsterdam' → 'IJMUIDEN', 'AMSTERDAM'); harbours without a linked
  //    built-in port become ports of their own.
  for (const h of harborList) {
    let p = byKey.get(h.id);
    if (!p) {
      p = { key: h.id, locode: null, harbor: h.id, name: h.name, lat: h.lat, lon: h.lon, r: h.size === 'mega' ? 8 : h.size === 'major' ? 5 : 3 };
      ports.push(p); byKey.set(h.id, p);
    }
    const parts = String(h.name).split(/[/(),]/).map((s) => s.trim()).filter(Boolean);
    for (const part of parts) addName(part, p);
    addName(h.name, p);
    addName(String(h.id).replace(/_/g, ' '), p);
  }
  const nameList = [...names.keys()];

  const pub = (p) => ({ id: p.key, locode: p.locode, harbor: p.harbor, name: p.name, lat: p.lat, lon: p.lon });

  const cc = (c) => (c === 'UK' ? 'GB' : c); // 'UKFXT', 'UK HUL'
  let hit = null; // the name the last successful match used (null for a LOCODE): selects the homonym group
  function byLocodeStr(s) {
    const m = s.match(/^([A-Z]{2}) ?([A-Z2-9]{3})$/);
    if (!m) return null;
    const p = byLocode.get(cc(m[1]) + m[2]) || null;
    if (p) hit = null;
    return p;
  }
  function matchName(s) {
    if (!s) return null;
    const exact = names.get(s);
    if (exact) { hit = s; return exact; }
    const c = s.replace(/ /g, '');
    if (compact.has(c)) { hit = compactName.get(c); return compact.get(c); }
    return null;
  }
  function fuzzy(s) {
    if (s.length < 5) return null;
    const max = s.length >= 10 ? 2 : 1;
    let best = null, bestD = max + 1, bestName = null;
    for (const n of nameList) {
      if (n.length < 5 || Math.abs(n.length - s.length) > max || (s.length < 7 && n.length === s.length)) continue;
      if (n[0] !== s[0] && (n[1] !== s[1] || s.length < 8)) continue; // typos rarely hit the first letter of a short name
      const d = editDistance(s, n, max);
      if (d < bestD) { bestD = d; best = names.get(n); bestName = n; if (d === 1 && max === 1) break; }
    }
    if (best) hit = bestName;
    return best;
  }
  /** A word cut off by the 20-character field ('… ROTTERD', '… HAMBUR') → the first port name it begins. */
  function truncated(w) {
    if (w.length < 6) return null;
    for (const n of nameList) if (n.length > w.length && n.startsWith(w) && !n.includes(' ')) { hit = n; return names.get(n); }
    return null;
  }
  /** Resolve one normalized candidate string. */
  function resolveOne(s, cut) {
    if (!s || NOT_A_PORT.has(s)) return null;
    let p = byLocodeStr(s) || matchName(s);
    if (p) return p;
    const words = s.split(' ').filter((w) => !NOISE.has(w));
    const t = words.join(' ');
    if (t && t !== s) { if (NOT_A_PORT.has(t)) return null; p = byLocodeStr(t) || matchName(t); if (p) return p; }
    // leading LOCODE followed by text or a terminal code: 'NLRTM ANCH', 'DKSKA 1', 'NL RTM2602', 'NLAMS01090DOCKX00018'
    const lead = s.match(/^([A-Z]{2}) ?([A-Z2-9]{3})(?![A-Z])/);
    if (lead) { p = byLocode.get(cc(lead[1]) + lead[2]); if (p) { hit = null; return p; } }
    // the longest prefix of words that names a port: 'HAMBURG GERMANY', 'ROTTERDAM BOTLEK BO' — not a part of a compound
    // name ('BERGEN OP ZOOM') and not a bare 2–3 letter abbreviation ('LA SEINE A ROUEN')
    for (let n = words.length - 1; n >= 1; n--) {
      const pre = words.slice(0, n).join(' ');
      if (pre.replace(/ /g, '').length < 4 || CONNECT.has(words[n])) continue;
      p = matchName(pre); if (p) return p;
    }
    // any single word ≥ 4 letters that names a port: 'ARRIVING ROTTERDAM', 'DK-VEJLE' — again not inside a compound name
    for (let i = 0; i < words.length; i++) {
      const w = words[i];
      if (w.length < 4 || CONNECT.has(words[i + 1]) || CONNECT.has(words[i - 1])) continue;
      p = matchName(w) || (w.length === 5 ? byLocodeStr(w) : null); if (p) return p; // … or a LOCODE: 'EEVAN-FIHEL'
      // country code glued to a name: 'GBTEES', 'DEBREMEN'
      const g = w.match(/^([A-Z]{2})([A-Z]{4,})$/);
      if (g && ISO2.has(g[1])) { p = matchName(g[2]); if (p) return p; }
    }
    if (cut && words.length) { p = truncated(words[words.length - 1]); if (p) return p; }
    if (t) { p = fuzzy(t); if (p) return p; }
    return null;
  }

  /** Raw destination → `{port, name}` (a known port and the name that matched), `{loc}` (a LOCODE without coordinates) or null. */
  function resolveRaw(key) {
    const norm = normalizeText(key);
    if (!norm || NOT_A_PORT.has(norm) || norm.split(' ').every((w) => NOISE.has(w))) return null; // 'FOR ORDERS', 'EGYPT'
    const cut = String(key).trim().length >= 19; // AIS destinations are 20 characters: the last word may be cut off
    let txt = String(key).toUpperCase();
    const via = txt.replace(/\s+VIA\s.*$/, ''); // 'DEBRV VIA NOK', 'US NEW VIA SKAW': the destination comes first
    if (normalizeText(via)) txt = via;
    // routes 'NLRTM>DEHAM', 'NL RTM => DE HAM', 'GB YMO > DE HAM': only the last leg is the destination;
    // shuttles 'GBPME<>GBFBU', "R'DAM <-> BOZ", 'FIHEL<>FIMHQ<>SESTO': the first end that resolves
    const marked = txt.replace(/<\s*[-=]*\s*>/g, '\u0001');
    const legs = marked.split(/\s*(?:[-=]+>|>+|→|\bTO\b)\s*/).filter((l) => normalizeText(l.replace(/\u0001/g, ' ')));
    const routed = legs.length > 1;
    const target = routed ? legs[legs.length - 1] : marked;
    const ends = target.split('\u0001').filter((e) => normalizeText(e));
    const cands = [];
    for (const e of ends) {
      const n = normalizeText(e);
      cands.push(n);
      for (const part of e.split(/[/,;()]|\s-\s|\s+-|-\s+/)) { const q = normalizeText(part); if (q && q !== n) cands.push(q); }
    }
    for (let i = 0; i < cands.length; i++) { const p = resolveOne(cands[i], cut && i === 0 && ends.length === 1); if (p) return { port: p, name: hit }; }
    const last = normalizeText(routed ? ends[ends.length - 1] : ends[0]);
    const m = last.match(/^([A-Z]{2}) ?([A-Z2-9]{3})$/);
    if (m && ISO2.has(cc(m[1])) && !NOISE.has(last) && (last.includes(' ') || !names.has(last))) {
      const code = cc(m[1]) + m[2];
      return { loc: { id: code, locode: code, harbor: null, name: String(key).trim(), lat: null, lon: null } };
    }
    return null;
  }

  const cache = new Map();
  /**
   * AIS destination text → `{id, locode, harbor, name, lat, lon}` (a known port), `{id: LOCODE, locode, name: raw, lat: null,
   * lon: null}` (a well-formed LOCODE we have no coordinates for), or null (not a port / unknown). With the vessel's
   * position, a name shared by ports far apart ('PORTLAND', 'NEWCASTLE', 'WILLEMSTAD') resolves to the nearest of them.
   */
  function resolveDestination(raw, lat, lon) {
    if (raw == null) return null;
    const key = String(raw);
    let r = cache.get(key);
    if (r === undefined) {
      r = resolveRaw(key);
      if (cache.size > 20000) cache.clear();
      cache.set(key, r);
    }
    if (!r) return null;
    if (r.loc) return { ...r.loc };
    let p = r.port;
    const g = r.name && homonyms.get(r.name);
    if (g && Number.isFinite(lat) && Number.isFinite(lon)) {
      let best = Infinity;
      for (const q of g) { const d = distKm(lat, lon, q.lat, q.lon); if (d < best) { best = d; p = q; } }
    }
    return pub(p);
  }

  // spatial bucket for nearestPort (2° cells)
  const buckets = new Map();
  const bk = (lat, lon) => `${Math.floor(lat / 2)},${Math.floor(lon / 2)}`;
  for (const p of ports) { const k = bk(p.lat, p.lon); if (!buckets.has(k)) buckets.set(k, []); buckets.get(k).push(p); }
  /**
   * The port a vessel at (lat, lon) is lying in: the nearest port whose in-port radius (`r`, default 3 km; larger for
   * sprawling ports such as Rotterdam) contains the point, or within `maxKm` when given. Null when none.
   */
  function nearestPort(lat, lon, { maxKm = null } = {}) {
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
    let best = null, bestScore = Infinity;
    const r0 = Math.floor(lat / 2), c0 = Math.floor(lon / 2);
    for (let r = r0 - 1; r <= r0 + 1; r++) for (let c = c0 - 1; c <= c0 + 1; c++) {
      const list = buckets.get(`${r},${((c + 90) % 180 + 180) % 180 - 90}`); // lon cells wrap at the antimeridian
      if (!list) continue;
      for (const p of list) {
        const d = distKm(lat, lon, p.lat, p.lon);
        const lim = maxKm != null ? Math.max(maxKm, p.r) : p.r;
        if (d > lim) continue;
        const score = d / lim; // prefer the port whose own radius best contains the point
        if (score < bestScore) { bestScore = score; best = p; }
      }
    }
    return best ? { ...pub(best), distKm: Math.round(distKm(lat, lon, best.lat, best.lon) * 100) / 100 } : null;
  }

  return { ports, byLocode, resolveDestination, nearestPort, port: (k) => (byKey.get(k) || byLocode.get(k) ? pub(byKey.get(k) || byLocode.get(k)) : null) };
}
